print("number is genreted gusse the number.")
while(ans):
    bull = 0
    cow  = 0
    user = input("enter Number :")
    user_data.append(user)
    for i in user:
        if i in actual:
            if user.index(i) == actual.index(i):
                cow += 1
            else:
                bull += 1
    print(f"cow : {cow} bull : {bull}")
    if(cow == 4):
        print(user_data)
